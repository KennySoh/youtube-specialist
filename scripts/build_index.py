#!/usr/bin/env python3
"""Generate <transcripts>/INDEX.md and validate every transcript file.

Validation checks:
- Frontmatter parses as YAML
- Required fields present (title, video_id, url, transcript_source)
- Body has ≥1 [mm:ss] timestamp line
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

import yaml

REQUIRED = ["title", "video_id", "url", "transcript_source"]
TS_LINE = re.compile(r"^\[\d{1,2}:\d{2}(?::\d{2})?\] ")


def parse_md(path: Path) -> tuple[dict, str]:
    text = path.read_text()
    if not text.startswith("---\n"):
        raise ValueError("missing frontmatter")
    _, fm_text, body = text.split("---\n", 2)
    fm = yaml.safe_load(fm_text) or {}
    return fm, body


def validate(path: Path) -> list[str]:
    errors: list[str] = []
    try:
        fm, body = parse_md(path)
    except Exception as e:  # noqa: BLE001
        return [f"parse error: {e}"]
    for key in REQUIRED:
        if not fm.get(key):
            errors.append(f"missing field: {key}")
    if not any(TS_LINE.match(line) for line in body.splitlines()):
        errors.append("no [mm:ss] timestamp lines in body")
    return errors


def build_index(transcripts_dir: Path) -> tuple[str, list[tuple[Path, list[str]]]]:
    rows = []
    issues = []
    for md in sorted(transcripts_dir.glob("*.md")):
        if md.name == "INDEX.md":
            continue
        errs = validate(md)
        if errs:
            issues.append((md, errs))
            continue
        fm, body = parse_md(md)
        word_count = sum(len(line.split()) for line in body.splitlines() if TS_LINE.match(line))
        rows.append(
            {
                "date": fm.get("published_at") or "",
                "title": fm.get("title") or md.stem,
                "url": fm.get("url") or "",
                "video_id": fm.get("video_id") or "",
                "duration": fm.get("duration_seconds") or 0,
                "source": fm.get("transcript_source") or "",
                "words": word_count,
                "file": md.name,
                "channel": fm.get("channel") or "",
            }
        )

    rows.sort(key=lambda r: r["date"], reverse=True)

    channel = next((r["channel"] for r in rows if r["channel"]), "")
    lines = [
        f"# {channel or 'Channel'} — Transcript Index",
        "",
        f"_{len(rows)} videos · auto-generated by `scripts/build_index.py`_",
        "",
        "| Date | Title | Source | Words | Link |",
        "|------|-------|--------|------:|------|",
    ]
    for r in rows:
        title = r["title"].replace("|", "\\|")
        lines.append(
            f"| {r['date']} | [{title}]({r['file']}) | {r['source']} | {r['words']} | [yt]({r['url']}) |"
        )

    return "\n".join(lines) + "\n", issues


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--dir", type=Path, required=True, help="youtuber/<slug>/transcripts")
    args = p.parse_args()

    index_md, issues = build_index(args.dir)
    (args.dir / "INDEX.md").write_text(index_md)

    if issues:
        print(f"⚠ {len(issues)} files with issues:")
        for path, errs in issues:
            print(f"  {path.name}")
            for e in errs:
                print(f"    - {e}")
    else:
        print("✓ all transcripts validated cleanly")
    print(f"→ wrote {args.dir / 'INDEX.md'}")


if __name__ == "__main__":
    main()
